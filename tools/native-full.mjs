// Generates the Full entry of @colibri-kit/native (src/full/index.js and types/full.d.ts).
// Full = everything in the Core entry, plus the SVG and safe-area entries, with the gesture versions taking the
// place of the Core components that share their names. The lists are read from the source, so Full cannot fall
// behind. Fails if two entries export the same name where neither is meant to replace the other.
import { parse } from "@babel/parser";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = path.join(root, "packages/colibri-native");

/** Every name a module exports, following `export * from` and `export { … } from` into relative files. */
function exportNames(file, seen = new Set()) {
  if (seen.has(file)) return [];
  seen.add(file);
  const names = [], ast = parse(fs.readFileSync(file, "utf8"), { sourceType: "module", plugins: file.endsWith(".ts") ? ["typescript"] : ["jsx"] }).program;
  const local = (source) => { const base = path.resolve(path.dirname(file), source); return [base, base + ".js", base + ".d.ts", base + ".ts", path.join(base, "index.js")].find((candidate) => fs.existsSync(candidate) && fs.statSync(candidate).isFile()); };
  for (const node of ast.body) {
    if (node.type === "ExportAllDeclaration" && node.source.value.startsWith(".")) names.push(...exportNames(local(node.source.value), seen));
    else if (node.type === "ExportNamedDeclaration") {
      if (node.exportKind === "type") continue;
      for (const spec of node.specifiers) if (spec.exportKind !== "type") names.push(spec.exported.name);
      const d = node.declaration;
      if (d?.id) { if (!/^TS(Interface|TypeAlias)/.test(d.type)) names.push(d.id.name); }
      else if (d?.declarations) for (const item of d.declarations) names.push(item.id.name);
    }
  }
  return [...new Set(names)];
}

const light = exportNames(path.join(pkg, "src/index.js"));
const svg = exportNames(path.join(pkg, "src/svg/index.js"));
const safeArea = exportNames(path.join(pkg, "src/safe-area/index.js"));
const gestures = exportNames(path.join(pkg, "src/gestures/index.js"));
const clashes = [...light, ...svg, ...safeArea].filter((name, index, all) => all.indexOf(name) !== index);
if (clashes.length) throw new Error(`The Core, SVG and safe-area entries export the same name: ${[...new Set(clashes)].join(", ")}`);
const upgraded = gestures.filter((name) => light.includes(name)), added = gestures.filter((name) => !light.includes(name));

const header = `// GENERATED by tools/native-full.mjs — do not edit. The Full entry: everything in the Core entry, the SVG and
// safe-area entries, and the gesture versions in place of the Core components with the same names.
// Needs react-native-reanimated, react-native-gesture-handler, react-native-svg and react-native-safe-area-context.
// Finger-driven versions that replace Core ones: ${upgraded.join(", ") || "none"}.
`;
const body = (ext) => `export * from "../index${ext}";
export * from "../svg/index${ext}";
export * from "../safe-area/index${ext}";
// Named exports win over the starred ones above, so these are the versions Full hands out.
export { ${gestures.join(", ")} } from "../gestures/index${ext}";
`;
fs.mkdirSync(path.join(pkg, "src/full"), { recursive: true });
fs.writeFileSync(path.join(pkg, "src/full/index.js"), header + body(".js"));
fs.writeFileSync(path.join(pkg, "types/full.d.ts"), header + `export * from "../index";
export * from "./svg";
export * from "./safe-area";
export { ${gestures.join(", ")} } from "./gestures";
`);
fs.writeFileSync(path.join(pkg, "entries.json"), JSON.stringify({ light: light.length, svg, safeArea, gestures: { upgraded, added } }, null, 2) + "\n");
console.log(`Full entry: ${light.length} Core exports, ${svg.length} SVG, ${safeArea.length} safe-area, ${upgraded.length} upgraded and ${added.length} added by gestures`);
