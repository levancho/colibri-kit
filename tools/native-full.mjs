// Generates the entry of @colibri-kit/native-full (src/index.js and types/index.d.ts).
// Full = everything in @colibri-kit/native-core, plus the SVG and safe-area parts, with the gesture versions taking
// the place of the Core components that share their names. The lists are read from the source, so Full cannot fall
// behind. Fails if two entries export the same name where neither is meant to replace the other.
import { parse } from "@babel/parser";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const core = path.join(root, "packages/colibri-native-core"), full = path.join(root, "packages/colibri-native-full");
/** Every name a module exports, following `export * from` and `export { … } from` into relative files. */
function exportNames(file, seen = new Set()) {
  if (seen.has(file)) return [];
  seen.add(file);
  const names = [], ast = parse(fs.readFileSync(file, "utf8"), { sourceType: "module", plugins: file.endsWith(".ts") ? ["typescript"] : ["jsx"] }).program;
  const local = (source) => { const base = path.resolve(path.dirname(file), source); return [base, base + ".js", base + ".d.ts", base + ".ts", path.join(base, "index.js")].find((candidate) => fs.existsSync(candidate) && fs.statSync(candidate).isFile()); };
  for (const node of ast.body) {
    if (node.type === "ExportAllDeclaration" && node.source.value.startsWith(".")) names.push(...exportNames(local(node.source.value), seen));
    else if (node.type === "ExportNamedDeclaration") {
      if (node.exportKind === "type") continue;
      for (const spec of node.specifiers) if (spec.exportKind !== "type") names.push(spec.exported.name);
      const d = node.declaration;
      if (d?.id) { if (!/^TS(Interface|TypeAlias)/.test(d.type)) names.push(d.id.name); }
      else if (d?.declarations) for (const item of d.declarations) names.push(item.id.name);
    }
  }
  return [...new Set(names)];
}

const coreNames = exportNames(path.join(core, "src/index.js"));
const svg = exportNames(path.join(full, "src/svg/index.js"));
const safeArea = exportNames(path.join(full, "src/safe-area/index.js"));
const gestures = exportNames(path.join(full, "src/gestures/index.js"));
const clashes = [...coreNames, ...svg, ...safeArea].filter((name, index, all) => all.indexOf(name) !== index);
if (clashes.length) throw new Error(`Core, the SVG part and the safe-area part export the same name: ${[...new Set(clashes)].join(", ")}`);
const upgraded = gestures.filter((name) => coreNames.includes(name)), added = gestures.filter((name) => !coreNames.includes(name));

const header = `// GENERATED by tools/native-full.mjs — do not edit. @colibri-kit/native-full: everything in @colibri-kit/native-core,
// the SVG and safe-area parts, and the gesture versions in place of the Core components with the same names.
// Finger-driven versions that replace Core ones: ${upgraded.join(", ") || "none"}.
`;
const body = (ext, dir) => `export * from "@colibri-kit/native-core";
export * from "./svg${dir ? "/index" : ""}${ext}";
export * from "./safe-area${dir ? "/index" : ""}${ext}";
// Named exports win over the starred ones above, so these are the versions Full hands out.
export { ${gestures.join(", ")} } from "./gestures${dir ? "/index" : ""}${ext}";
`;
fs.writeFileSync(path.join(full, "src/index.js"), header + body(".js", true));
fs.writeFileSync(path.join(full, "types/index.d.ts"), header + body("", false));
fs.writeFileSync(path.join(full, "entries.json"), JSON.stringify({ core: coreNames.length, svg, safeArea, gestures: { upgraded, added } }, null, 2) + "\n");
console.log(`Full: ${coreNames.length} Core exports, ${svg.length} SVG, ${safeArea.length} safe-area, ${upgraded.length} upgraded and ${added.length} added by gestures`);
