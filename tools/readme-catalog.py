#!/usr/bin/env python3
"""Rewrites the catalog block in README.md (between CATALOG markers) from the kitchen-sink catalog."""
import pathlib, re, sys
HERE = pathlib.Path(__file__).parent; sys.path.insert(0, str(HERE))
from sink_catalog_more import C
import sink_catalog_motion, sink_catalog_ai, sink_catalog_blocks  # noqa: Motion, Theming
L = {"done": "✅ done", "partial": "🟡 partial", "planned": "⚪ planned", "css": "🔷 structure (markup/CSS only)"}
out = ["<!-- CATALOG:START (generated by tools/readme-catalog.py) -->", "## Component catalog", "",
       "Live demos: `examples/kitchen-sink.html` (served at http://localhost:8395/examples/kitchen-sink.html).", "",
       "Status: " + " · ".join(f"{v} {sum(c['status']==k for c in C)}" for k, v in L.items()), ""]
for g in ["Base", "Navigation", "Forms", "Conversation", "AI Elements", "Sidebar blocks", "Login blocks", "Signup blocks", "Motion", "Theming"]:
    out += [f"### {g}", "", "| Colibri (`data-ui`) | Status | Metronic | shadcn |", "|---|---|---|---|"]
    out += [f"| {c['name']} (`{c['id']}`) | {L[c['status']]} | {c['metronic']} | {c['shadcn']} |" for c in sorted([c for c in C if c['group']==g], key=lambda c: c['name'])]
    out.append("")
out.append("<!-- CATALOG:END -->")
r = (HERE.parent / "README.md"); t = r.read_text(); block = "\n".join(out)
t = re.sub(r"<!-- CATALOG:START.*?CATALOG:END -->", lambda m: block, t, flags=re.S) if "CATALOG:START" in t else t.rstrip() + "\n\n" + block + "\n"
r.write_text(t); print("README catalog:", len(C))
