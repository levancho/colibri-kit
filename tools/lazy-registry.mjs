// Maintainer build: derive src/core/lazy-registry.js from src/core/registry.js.
// Each entry becomes a loader that imports only the module that owns the controller, so auto-lazy.js
// downloads code for the components a page actually uses. Run: node tools/lazy-registry.mjs [--check]
import fs from "node:fs"; import path from "node:path"; import url from "node:url";
const root = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), ".."), core = path.join(root, "src/core");
const source = fs.readFileSync(path.join(core, "registry.js"), "utf8");

const named = new Map(), namespaces = new Map(); // identifier -> module
for (const m of source.matchAll(/import\s*\{([^}]+)\}\s*from\s*"(\.\/[\w-]+\.js)"/g)) for (const id of m[1].split(",").map((s) => s.trim()).filter(Boolean)) named.set(id, m[2]);
for (const m of source.matchAll(/import\s*\*\s*as\s+(\w+)\s+from\s*"(\.\/[\w-]+\.js)"/g)) namespaces.set(m[1], m[2]);

const body = source.slice(source.indexOf("export const registry = {") + "export const registry = {".length, source.lastIndexOf("};"));
const entries = [...body.matchAll(/(?:"([\w-]+)"|([\w$]+))\s*:\s*([\w$.]+(?:\([\w$.]+\))?)\s*,/g)].map((m) => [m[1] || m[2], m[3]]);

/** { module, name } for `createX` or `NS.createX`. */
function ref(expr) {
  const [a, b] = expr.split(".");
  if (b) { if (!namespaces.has(a)) throw new Error(`registry.js: unknown namespace in ${expr}`); return { module: namespaces.get(a), name: b }; }
  if (!named.has(a)) throw new Error(`registry.js: ${a} is not imported`);
  return { module: named.get(a), name: a };
}
function loader(expr) {
  const wrapped = /^([\w$.]+)\(([\w$.]+)\)$/.exec(expr);
  if (!wrapped) { const r = ref(expr); return `() => import("${r.module}").then((m) => m.${r.name})`; }
  const w = ref(wrapped[1]), inner = ref(wrapped[2]);
  return w.module === inner.module
    ? `() => import("${w.module}").then((m) => m.${w.name}(m.${inner.name}))`
    : `() => Promise.all([import("${w.module}"), import("${inner.module}")]).then(([w, m]) => w.${w.name}(m.${inner.name}))`;
}

const out = `// GENERATED by tools/lazy-registry.mjs from registry.js. Do not edit.
// data-ui name -> loader returning that component's controller factory. Used by auto-lazy.js.
export const loaders = {
${entries.map(([name, expr]) => `  ${/^[\w$]+$/.test(name) ? name : JSON.stringify(name)}: ${loader(expr)},`).join("\n")}
};
`;
const file = path.join(core, "lazy-registry.js");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== out) { console.error("src/core/lazy-registry.js is stale: run node tools/lazy-registry.mjs"); process.exit(1); }
} else { fs.writeFileSync(file, out); console.log(`lazy-registry.js: ${entries.length} loaders`); }
