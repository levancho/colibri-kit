"""Generate native source, not runtime wrappers, from the application contracts."""
import json,html,pathlib,sys
sys.path.insert(0,str(pathlib.Path(__file__).parent))
from catalog import S
ROOT=pathlib.Path(__file__).resolve().parents[2]
VOID={'img','input','br','hr'}
def binding(v):return isinstance(v,dict) and 'value'in v
def resolve(path,env):
 if ' == ' in path:
  a,b=path.split(' == ',1)
  return resolve(a,env)==(json.loads(b) if b.startswith('"') else resolve(b,env))
 v=env
 for part in path.split('.'):v=v[part]
 return v

def render(n,kind,env=None,level=0):
 if isinstance(n,str):return json.dumps(n) if kind=='react' else html.escape(n)
 if isinstance(n,dict) and 'slot'in n:
  return {'react':'children','ftl':'[#nested]','thymeleaf':'<section th:replace="${content}"></section>','html':''}[kind]
 if binding(n):
  x=n['value']
  if kind=='react':return x
  if kind=='ftl':return '${'+x+'}'
  if kind=='thymeleaf':return '<span th:text="${'+x+'}"></span>'
  return html.escape(str(resolve(x,env)))
 if 'each'in n:
  path,name=n['each'],n['as'];body=n['node']
  if kind=='react':return f'{path}.map(({name}, index) => '+render(body,kind,level=level+1).replace('h(', 'h(',1).replace('{', '{key:'+name+'.id ?? '+name+'.name ?? index,',1)+')'
  if kind=='ftl':return '[#list '+path+' as '+name+']'+render(body,kind,level=level+1)+'[/#list]'
  if kind=='thymeleaf':
   body={**body,'attrs':{'th:each':f'{name} : ${{{path}}}',**body.get('attrs',{})}}
   return render(body,kind,level=level+1)
  return ''.join(render(body,kind,{**env,name:item},level+1) for item in resolve(path,env))
 tag,attrs,kids=n['tag'],dict(n['attrs']),n['children']
 if kind!='react' and tag=='select':attrs.pop('value',None)
 if kind=='react':
  attrs.pop('selected',None)
  attrs={ {'class':'className','for':'htmlFor','maxlength':'maxLength','datetime':'dateTime'}.get(k,k):v for k,v in attrs.items()}
  # Uncontrolled form inputs retain edits across unrelated parent renders.
  if 'value'in attrs and tag in ('input','textarea'):attrs['defaultValue']=attrs.pop('value')
  props=', '.join(json.dumps(k)+':'+(v['value'] if binding(v) else json.dumps(v)) for k,v in attrs.items())
  if tag=='input' and level>0:props+=', ...(values ? {value: values[field.name] ?? "", defaultValue:undefined, onChange:event=>onValuesChange?.({...values,[field.name]:event.target.value})} : {})'
  if level==0 and tag=='form':props+=', key:JSON.stringify([recordKey ?? model.id ?? null,resetKey ?? null])'
  if tag=='select' and 'value'in attrs:props+=', onChange:()=>{}'
  if level==0:props+=', onClick:handleClick, onSubmit:handleSubmit, onInput:handleInput, onChange:handleChange'
  if level==0 and attrs.get('data-application-component')=='shell':props+=', ref:shellRef'
  return 'h('+json.dumps(tag)+', {'+props+'}'+('' if not kids else ', '+', '.join(render(c,kind,level=level+1) for c in kids))+')'
 if kind=='thymeleaf':
  if level==0:attrs={'xmlns:th':'http://www.thymeleaf.org','th:fragment':'component(model, content)' if attrs.get('data-application-component')=='shell' else 'component(model)',**attrs}
  dynamic=[];out={}
  for k,v in attrs.items():
   if binding(v) and k=='selected':out['th:selected']='${'+v['value']+'}'
   elif binding(v):dynamic.append(k+'=${'+v['value']+'}')
   else:out[k]=v
  if dynamic:out['th:attr']=','.join(dynamic)
  attrs=out
  if len(kids)==1 and binding(kids[0]):attrs['th:text']='${'+kids[0]['value']+'}';kids=[]
 a=''
 for k,v in attrs.items():
  if k=='selected' and binding(v):
   if kind=='ftl':a+='[#if '+v['value']+'] selected[/#if]'
   elif kind=='html' and resolve(v['value'],env):a+=' selected'
   continue
  if v is True:a+=' '+k;continue
  if binding(v):v=('${('+v['value']+')?c}' if ' == ' in v['value'] else '${'+v['value']+'}') if kind=='ftl' else str(resolve(v['value'],env)).lower() if isinstance(resolve(v['value'],env),bool) else str(resolve(v['value'],env))
  a+=' '+k+'="'+html.escape(str(v),quote=True)+'"'
 return '<'+tag+a+'>'+('' if tag in VOID else ''.join(render(c,kind,env,level+1) for c in kids)+'</'+tag+'>')

react=['// Generated by tools/applications/generate.py. Native React elements and caller-owned data.', 'import { createElement as h, useEffect, useRef } from "react";', '''function handlers(onAction, onSubmit) {
 return {
  handleInput(event) { if(event.target.matches('[data-app-filter]')) for(const row of event.currentTarget.querySelectorAll('tbody tr')) row.hidden=!row.textContent.toLowerCase().includes(event.target.value.toLowerCase()); },
  handleChange(event) {if(onAction && event.target.matches('[data-ticket-status],[data-ticket-assignee]'))onAction({action:event.target.matches('[data-ticket-status]')?'ticket-status':'assign-ticket',value:event.target.value,element:event.target,originalEvent:event});},
  handleClick(event) { const button=event.target.closest('[data-app-action]'); if(button && onAction) {event.preventDefault(); onAction({action:button.dataset.appAction,id:button.dataset.id,element:button,originalEvent:event});} },
  handleSubmit(event) { if(onSubmit) {event.preventDefault();onSubmit({form:event.target.dataset.appForm,...formSubmission(event.target,event.nativeEvent?.submitter),element:event.target,originalEvent:event});} }
 };
}''']
react.append('import { formSubmission } from "../core/form-data.js";')
react.append('import { createApplicationShell } from "../core/application-shell.js";')
meta={}
for key,s in S.items():
 tree=s['tree'];tree['attrs']['data-application-component']=key
 name=s['name'];meta[key]={'name':name,'model':s['model']}
 extra='const shellRef=useRef(null); useEffect(()=>{const api=createApplicationShell(shellRef.current);return ()=>api.destroy();},[]);' if key=='shell' else ''
 react.append(f'export function {name}({{ model, onAction, onSubmit, children, recordKey, resetKey, values, onValuesChange }}) {{\n const {{handleClick,handleSubmit,handleInput,handleChange}}=handlers(onAction,onSubmit);\n {extra}\n return '+render(tree,'react')+';\n}')
 (ROOT/'freemarker'/f'application-{key}.ftl').write_text('[#ftl output_format="HTML" auto_esc=true]\n[#macro component model]\n'+render(tree,'ftl')+'\n[/#macro]\n')
 (ROOT/'thymeleaf'/f'application-{key}.html').write_text(render(tree,'thymeleaf')+'\n')
 s['html']=render(tree,'html',{'model':s['model']})
(ROOT/'src/react/application-components.js').write_text('\n\n'.join(react)+'\n')
(ROOT/'examples/application-models.json').write_text(json.dumps(meta,indent=2)+'\n')
