#!/usr/bin/env python3
"""Builds registry/colibri.json: the machine-readable catalog used by the CLI (bin/colibri.mjs),
the MCP server (bin/colibri-mcp.mjs) and the AI skill (skills/colibri-ui/SKILL.md)."""
import json, pathlib, re, sys, html as H
HERE = pathlib.Path(__file__).parent; ROOT = HERE.parent; sys.path.insert(0, str(HERE))
from sink_catalog_more import C
import sink_catalog_motion, sink_catalog_ai, sink_catalog_blocks  # noqa
import sink_catalog_css, sink_catalog_radix, sink_catalog_applications
from sink_info import INFO
from sink_code import FTL, IMP
from sink_pretty import pretty
from sink_adapters import adapters
import sink_events
BEHAVIOUR = sink_events.extract()
pkg = json.loads((ROOT / "package.json").read_text())
items = []
for c in C:
    tabs,support=adapters(c)
    snippets={k:src for k,_,src in tabs}
    t, what, when = INFO[c["id"]]
    parts = sorted(set(re.findall(r'data-ui-part="([a-z0-9-]+)"', c["demo"])))
    uis = sorted(set(re.findall(r'data-ui="([a-z0-9-]+)"', c["demo"])))
    kind = "block" if c["group"].endswith("blocks") else "motion" if c["group"] in ("Motion", "Theming") else "component"
    items.append({"name": c["id"], "title": t, "type": kind, "group": c["group"], "status": c["status"], "description": what, "whenToUse": when,
                  "shadcn": c["shadcn"], "metronic": c["metronic"], "accessibility": c["notes"], "parts": parts, "uses": [u for u in uis if u != c["id"]],
                  "controller": c["id"] if c["id"] in uis else None, "html": pretty(c.get("public_html", c["demo"])), "freemarker": snippets.get("ftl"), "react": snippets.get("react"), "thymeleaf": snippets.get("thymeleaf"), "javascript": snippets.get("js"), "adapters":snippets, "support":support})
# Events and controller API are read from src/core, so they cannot drift from the code.
for item in items:
    b = BEHAVIOUR.get(item["name"])
    item["events"] = b["events"] if b else []
    item["api"] = b["api"] if b else []
out = {"$schema": "https://colibri-ui.local/schema/registry.json", "name": "colibri-ui", "version": pkg.get("version", "0.0.0"),
       "files": {"applications": "packages/colibri-css/dist/colibri-applications.css", "core": "src/core/", "auto": "src/core/auto.js", "elements": "src/elements/all.js", "theme": "themes/colibri.css", "motion": "themes/motion.css", "freemarker": "freemarker/ui.ftl", "thymeleaf": "thymeleaf/", "css": "packages/colibri-css/dist/colibri.css", "bridge": "packages/colibri-css/dist/colibri-ui-bridge.css"},
       "rules": ["Markup contract: data-ui=\"name\" roots, data-ui-part=\"part\" children; state in data-state / aria-* / hidden.",
                 "Never style by JS; theme only through --ui-* tokens in themes/colibri.css (or your own CSS).",
                 "Events are ui:* CustomEvents that bubble; cancelable ones can be preventDefault()-ed.",
                 "Forms: wrap each control in data-ui=field (label, control, description, error).",
                 "Option sets: use toggle-group / radio-group; menus: dropdown-menu; overlays: dialog/sheet/popover.",
                 "Compose blocks from components; do not invent new data-ui names for layouts (use classes).", "Application entries use data-application-component and the documented optional application controllers, not invented data-ui registrations. Check support and adapters per entry."],
       "items": items}
(ROOT / "registry").mkdir(exist_ok=True)
(ROOT / "registry" / "colibri.json").write_text(json.dumps(out, ensure_ascii=False, indent=1))
print(f"registry/colibri.json: {len(items)} items")

# Machine-readable support matrix; the site links this same contract.
(ROOT/'site/src/framework-support.json').write_text(json.dumps([{key:item[key] for key in ('name','title','support')} for item in items],indent=2)+'\n')

# The skill reference carries the same generated table between markers.
ref = ROOT / 'skills/colibri-kit/reference/components.md'
text, start, end = ref.read_text(), '<!-- events:start (generated by tools/registry.py) -->', '<!-- events:end -->'
section = f"{start}\n## Events and controller API\n\n{sink_events.markdown(BEHAVIOUR)}{end}"
text = re.sub(re.escape(start) + r'.*?' + re.escape(end), lambda m: section, text, flags=re.S) if start in text else text.rstrip('\n') + '\n\n' + section + '\n'
ref.write_text(text)
